// Builds DTCG token files into CSS custom properties and a resolved JSON file.
// Primitives become --uf-<path>; theme tokens reference them with var() so
// overriding a primitive (e.g. --uf-palette-accent-600) cascades to every theme.
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const read = async (file) => JSON.parse(await readFile(new URL(`src/${file}`, root), 'utf8'));

const base = await read('base.tokens.json');
const light = await read('light.tokens.json');
const dark = await read('dark.tokens.json');

/** Flattens a DTCG tree into [{ path, value }], skipping $-prefixed metadata keys. */
function flatten(node, path = []) {
  if (node && typeof node === 'object' && '$value' in node) return [{ path, value: node.$value }];
  return Object.entries(node)
    .filter(([key]) => !key.startsWith('$'))
    .flatMap(([key, child]) => flatten(child, [...path, key]));
}

const cssName = (path) => `--uf-${path.join('-')}`;
const reference = /^\{([^}]+)\}$/;

const baseTokens = flatten(base);
const baseByPath = new Map(baseTokens.map((t) => [t.path.join('.'), t.value]));

/** DTCG gradient stops ([{ color, position }]) -> linear-gradient(). */
const gradient = (stops, color) =>
  `linear-gradient(135deg, ${stops.map((s) => `${color(s.color)} ${Math.round(s.position * 100)}%`).join(', ')})`;

function toCss(value) {
  if (Array.isArray(value)) return gradient(value, toCss);
  const match = typeof value === 'string' && value.match(reference);
  if (!match) return String(value);
  if (!baseByPath.has(match[1])) throw new Error(`Unknown token reference ${value}`);
  return `var(${cssName(match[1].split('.'))})`;
}

function resolve(value) {
  if (Array.isArray(value)) return gradient(value, resolve);
  const match = typeof value === 'string' && value.match(reference);
  return match ? baseByPath.get(match[1]) : value;
}

const declarations = (tokens, indent) =>
  tokens.map((t) => `${indent}${cssName(t.path)}: ${toCss(t.value)};`).join('\n');

const lightTokens = flatten(light);
const darkTokens = flatten(dark);

// Every Unframed tag. @unframed/core's tests check that none is missing.
const tags = [
  'uf-accordion', 'uf-accordion-item', 'uf-avatar', 'uf-badge', 'uf-breadcrumb-item', 'uf-breadcrumbs', 'uf-button',
  'uf-calendar', 'uf-card', 'uf-checkbox', 'uf-checkbox-group', 'uf-combobox', 'uf-date-picker', 'uf-date-range-picker', 'uf-dialog',
  'uf-drawer', 'uf-dropdown', 'uf-file-upload', 'uf-icon', 'uf-input', 'uf-menu', 'uf-menu-item', 'uf-pagination', 'uf-popover',
  'uf-progress', 'uf-radio', 'uf-radio-group', 'uf-select', 'uf-slider', 'uf-spinner', 'uf-switch', 'uf-tab',
  'uf-tab-panel', 'uf-table', 'uf-tabs', 'uf-textarea', 'uf-toaster', 'uf-tooltip',
];

// Server-rendered pages (Next.js, Nuxt, Angular SSR) show the HTML before the
// components' JavaScript loads. Until then, components are invisible but keep
// their place, and content that only shows once opened takes no space: a
// closed dialog's text, a menu's items, a select's options.
const undefinedComponents = `/* Before the components load: no flash of raw content on server-rendered pages. */
:where(${tags.join(', ')}):not(:defined) {
  visibility: hidden;
}

:where(uf-dialog, uf-drawer, uf-toaster, uf-tab-panel):not(:defined),
:where(uf-dropdown, uf-popover):not(:defined) > :not([slot]),
:where(uf-select, uf-combobox):not(:defined) > :where(option, optgroup),
uf-accordion-item:not(:defined):not([open]) > :not([slot]) {
  display: none;
}`;

const css = `/* @unframed/tokens — generated by scripts/build.mjs, do not edit. */
:root {
${declarations(baseTokens, '  ')}
}

:root,
[data-uf-theme='light'] {
  color-scheme: light;
${declarations(lightTokens, '  ')}
}

[data-uf-theme='dark'] {
  color-scheme: dark;
${declarations(darkTokens, '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-uf-theme='light']) {
    color-scheme: dark;
${declarations(darkTokens, '    ')}
  }
}

${undefinedComponents}
`;

const resolved = {
  base: Object.fromEntries(baseTokens.map((t) => [cssName(t.path), resolve(t.value)])),
  light: Object.fromEntries(lightTokens.map((t) => [cssName(t.path), resolve(t.value)])),
  dark: Object.fromEntries(darkTokens.map((t) => [cssName(t.path), resolve(t.value)])),
};

await mkdir(new URL('dist/', root), { recursive: true });
await writeFile(new URL('dist/tokens.css', root), css);
await writeFile(new URL('dist/tokens.json', root), `${JSON.stringify(resolved, null, 2)}\n`);
console.log(`tokens: ${baseTokens.length} primitives, ${lightTokens.length} semantic`);

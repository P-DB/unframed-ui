// Generates typed React wrappers for every custom element in @unframed/core's
// custom-elements.json. Custom events like `uf-change` become `onUfChange` props.
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { coreImportPath } from '../../../scripts/form-models.mjs';

const root = new URL('../', import.meta.url);
const manifestUrl = new URL('../core/custom-elements.json', root);
const outDir = new URL('src/generated/', root);

const manifest = JSON.parse(await readFile(manifestUrl, 'utf8'));

const pascal = (name) => name.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());

const elements = manifest.modules.flatMap((mod) =>
  (mod.declarations ?? [])
    .filter((d) => d.customElement && d.tagName)
    .map((d) => ({ ...d, modulePath: mod.path })),
);

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const header = '// Generated by scripts/generate.mjs from @unframed/core/custom-elements.json. Do not edit.\n';

for (const el of elements) {
  const events = (el.events ?? []).filter((e) => e.name);
  const eventTypes = events.map((e) => {
    const type = e.type?.text ?? 'Event';
    return `    on${pascal(e.name)}: '${e.name}' as EventName<${type}>,`;
  });

  // Detail types like TabChangeDetail are exported from @unframed/core's entry point.
  const builtIns = new Set(['Event', 'CustomEvent']);
  const detailTypes = [
    ...new Set(events.flatMap((e) => e.type?.text.match(/\b[A-Z]\w+/g) ?? []).filter((t) => !builtIns.has(t))),
  ];
  const typeImport = detailTypes.length ? `import type { ${detailTypes.join(', ')} } from '@unframed/core';\n` : '';

  // Every property and its attribute, so server rendering can write the attributes.
  const fields = (el.members ?? []).filter((m) => m.kind === 'field' && !m.readonly);
  // `value` and `checked` have no attribute of their own: their attributes set the
  // defaults (defaultValue, defaultChecked), which is what a server render needs.
  const attributeOf = (field) =>
    (el.attributes ?? []).find((a) => a.fieldName === field)?.name ??
    (el.attributes ?? []).find((a) => a.name === field)?.name ??
    null;
  const serverAttributes = fields.map((f) => `    ${f.name}: ${JSON.stringify(attributeOf(f.name))},`).join('\n');

  // 'use client': the wrappers use hooks, so in React Server Components (the
  // Next.js App Router) each one is a client component, usable from server ones.
  const source = `'use client';\n${header}import * as React from 'react';
import { createComponent${events.length ? ', type EventName' : ''} } from '@lit/react';
import { ${el.name} as ${el.name}Element } from '${coreImportPath(el.modulePath)}';
${typeImport}import { withServerAttributes } from '../server-attributes.js';

${el.summary ? `/** ${el.summary} */\n` : ''}export const ${el.name} = withServerAttributes(
  createComponent({
    tagName: '${el.tagName}',
    elementClass: ${el.name}Element,
    react: React,
    displayName: '${el.name}',
    events: {${eventTypes.length ? `\n${eventTypes.map((e) => `  ${e}`).join('\n')}\n    ` : ''}},
  }),
  '${el.tagName}',
  {${serverAttributes ? `\n${serverAttributes}\n` : ''}},
);
`;
  await writeFile(new URL(`${el.tagName}.ts`, outDir), source);
}

const index = header + elements.map((el) => `export { ${el.name} } from './${el.tagName}.js';`).join('\n') + '\n';
await writeFile(new URL('index.ts', outDir), index);

console.log(`react: generated ${elements.length} wrapper(s): ${elements.map((e) => e.tagName).join(', ')}`);

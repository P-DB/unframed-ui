// Generates a Vue component for every custom element in @unframed/core's
// custom-elements.json, with typed props, typed event handlers and v-model
// for form controls.
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { coreImportPath, formModels, pascal, readElements, warnMissingModels } from '../../../scripts/form-models.mjs';

const root = new URL('../', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('../core/custom-elements.json', root), 'utf8'));
const outDir = new URL('src/generated/', root);

const elements = readElements(manifest);
warnMissingModels(elements);

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const header = '// Generated by scripts/generate.mjs from @unframed/core/custom-elements.json. Do not edit.\n';
const builtInTypes = new Set(['Event', 'CustomEvent']);

for (const el of elements) {
  const classType = `${el.name}Element`;
  // Public writable fields become props, typed from the element class itself.
  const fields = [
    ...new Set([
      ...(el.attributes ?? []).map((a) => a.fieldName ?? a.name),
      ...(el.members ?? []).filter((m) => m.kind === 'field' && !m.readonly).map((m) => m.name),
    ]),
  ].filter((f) => /^[a-zA-Z_$][\w$]*$/.test(f) && f !== 'form' && f !== 'validity');
  const readonly = new Set((el.members ?? []).filter((m) => m.kind === 'field' && m.readonly).map((m) => m.name));
  const props = fields.filter((f) => !readonly.has(f));

  const events = (el.events ?? []).filter((e) => e.name);
  const detailTypes = [
    ...new Set(events.flatMap((e) => e.type?.text.match(/\b[A-Z]\w+/g) ?? []).filter((t) => !builtInTypes.has(t))),
  ];

  const docs = (text) => (text ? `  /** ${text.replace(/\*\//g, '*\\/').replace(/\n+/g, ' ')} */\n` : '');
  const propLines = props.map((p) => {
    const doc = (el.attributes ?? []).find((a) => (a.fieldName ?? a.name) === p)?.description ?? (el.members ?? []).find((m) => m.name === p)?.description;
    return `${docs(doc)}  ${p}?: ${classType}['${p}'];`;
  });
  const eventLines = events.map((e) => `${docs(e.description)}  on${pascal(e.name)}?: (event: ${e.type?.text ?? 'Event'}) => void;`);

  const model = formModels[el.tagName];
  const modelType = model ? `${classType}['${model.prop}']` : 'never';

  const source = `${header}import type { ${el.name} as ${classType}${detailTypes.length ? `, ${detailTypes.join(', ')}` : ''} } from '@unframed/core';
import '${coreImportPath(el.modulePath)}';
import { createWrapper } from '../create-wrapper.js';

export interface ${el.name}Props {
${[...propLines, ...eventLines].join('\n')}
}

${el.summary ? `/** ${el.summary}${model ? ` Supports \`v-model\` (binds \`${model.prop}\`).` : ''} */\n` : ''}export const ${el.name} = createWrapper<${el.name}Props, ${modelType}>(
  '${el.tagName}',
  '${el.name}',
  ${JSON.stringify(props)},${model ? `\n  { prop: '${model.prop}', event: '${model.event}' },` : ''}
);
`;
  await writeFile(new URL(`${el.tagName}.ts`, outDir), source);
}

const names = elements.map((el) => el.name);
const index = `${header}import type { App } from 'vue';
${elements.map((el) => `import { ${el.name} } from './${el.tagName}.js';`).join('\n')}

export { ${names.join(', ')} };
${elements.map((el) => `export type { ${el.name}Props } from './${el.tagName}.js';`).join('\n')}

/** Registers every component globally: \`app.use(UnframedVue)\`. */
export const UnframedVue = {
  install(app: App): void {
${names.map((n) => `    app.component('${n}', ${n});`).join('\n')}
  },
};

declare module 'vue' {
  interface GlobalComponents {
${names.map((n) => `    ${n}: typeof ${n};`).join('\n')}
  }
}
`;
await writeFile(new URL('index.ts', outDir), index);
console.log(`vue: generated ${elements.length} component(s)`);

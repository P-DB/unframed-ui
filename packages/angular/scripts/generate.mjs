// Generates Angular wrappers from @unframed/core's custom-elements.json:
// - a standalone component per element, whose host *is* the custom element,
//   with typed inputs (booleans and numbers converted from attributes) and
//   typed outputs for custom events;
// - ControlValueAccessor directives so Angular forms work with form controls.
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { coreImportPath, formModels, pascal, readElements, warnMissingModels } from '../../../scripts/form-models.mjs';

const root = new URL('../', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('../core/custom-elements.json', root), 'utf8'));
const outDir = new URL('src/lib/generated/', root);

const elements = readElements(manifest);
warnMissingModels(elements);

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const header = '// Generated by scripts/generate.mjs from @unframed/core/custom-elements.json. Do not edit.\n';
const builtInTypes = new Set(['Event', 'CustomEvent']);
const camel = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const doc = (text, indent = '  ') => (text ? `${indent}/** ${text.replace(/\*\//g, '*\\/').replace(/\n+/g, ' ')} */\n` : '');

const typeImports = new Set();
const sideEffectImports = new Set();

const components = elements.map((el) => {
  const classType = `${el.name}Element`;
  typeImports.add(`${el.name} as ${classType}`);
  sideEffectImports.add(coreImportPath(el.modulePath));

  const readonly = new Set((el.members ?? []).filter((m) => m.kind === 'field' && m.readonly).map((m) => m.name));
  const fields = new Map();
  for (const a of el.attributes ?? []) fields.set(a.fieldName ?? a.name, { type: a.type?.text ?? '', description: a.description });
  for (const m of el.members ?? []) {
    if (m.kind === 'field' && !fields.has(m.name)) fields.set(m.name, { type: m.type?.text ?? '', description: m.description });
  }
  const inputs = [...fields].filter(([name]) => /^[a-zA-Z_$][\w$]*$/.test(name) && !readonly.has(name) && name !== 'form' && name !== 'validity');

  const inputLines = inputs.map(([name, { type, description }]) => {
    const transform = /^boolean\b/.test(type) ? ', { transform: booleanAttribute }' : /^number\b/.test(type) ? ', { transform: numberAttribute }' : '';
    const setterType = transform.includes('boolean') ? `${classType}['${name}'] | ''` : transform.includes('number') ? `${classType}['${name}'] | string` : `${classType}['${name}']`;
    return `${doc(description)}  @Input(${transform ? transform.slice(2) : ''}) set ${name}(value: ${setterType}) {
    this.el.${name} = value as ${classType}['${name}'];
  }
  get ${name}(): ${classType}['${name}'] {
    return this.el.${name};
  }`;
  });

  const events = (el.events ?? []).filter((e) => e.name && e.name.startsWith('uf-'));
  for (const e of events) for (const t of e.type?.text.match(/\b[A-Z]\w+/g) ?? []) if (!builtInTypes.has(t)) typeImports.add(t);
  const outputLines = events.map(
    (e) => `${doc(e.description)}  @Output('${e.name}') readonly ${camel(e.name)} = new EventEmitter<${e.type?.text ?? 'Event'}>();`,
  );
  const listen = events.map((e) => `    this.el.addEventListener('${e.name}', (event) => this.${camel(e.name)}.emit(event as ${e.type?.text ?? 'Event'}));`);

  // Properties the user can change besides the model value: an \`<prop>Change\`
  // output enables two-way binding, e.g. [(indeterminate)].
  const model = formModels[el.tagName];
  for (const prop of model?.synced ?? []) {
    outputLines.push(`${doc(`Emits the new \`${prop}\` when the user changes it, for \`[(${prop})]\`.`)}  @Output() readonly ${prop}Change = new EventEmitter<${classType}['${prop}']>();`);
    listen.push(`    this.el.addEventListener('${model.event}', () => this.${prop}Change.emit(this.el.${prop}));`);
  }

  return `${el.summary ? `/** ${el.summary} */\n` : ''}@Component({
  selector: '${el.tagName}',
  template: '<ng-content />',
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class ${el.name} {
  /** The underlying \`<${el.tagName}>\` element, for its methods. */
  readonly el: ${classType} = inject<ElementRef<${classType}>>(ElementRef).nativeElement;

${[...inputLines, ...outputLines].join('\n\n')}
${listen.length ? `\n  constructor() {\n${listen.join('\n')}\n  }\n` : ''}}
`;
});

const componentsFile = `${header}import { booleanAttribute, ChangeDetectionStrategy, Component, ElementRef, EventEmitter, inject, Input, numberAttribute, Output } from '@angular/core';
import type { ${[...typeImports].join(', ')} } from '@unframed/core';
${[...sideEffectImports].sort().map((p) => `import '${p}';`).join('\n')}

${components.join('\n')}
export const UF_COMPONENTS = [${elements.map((e) => e.name).join(', ')}] as const;
`;
await writeFile(new URL('components.ts', outDir), componentsFile);

// One value accessor per (property, event) pair.
const groups = new Map();
for (const [tag, model] of Object.entries(formModels)) {
  const key = `${model.prop}:${model.event}:${model.type}`;
  if (!groups.has(key)) groups.set(key, { ...model, tags: [] });
  groups.get(key).tags.push(tag);
}
const accessorNames = {
  'value:input:string': 'UfTextValueAccessor',
  'value:change:string': 'UfSelectValueAccessor',
  'checked:change:boolean': 'UfCheckedValueAccessor',
  'value:change:string[]': 'UfArrayValueAccessor',
};
const emptyValues = { string: "''", boolean: 'false', 'string[]': '[]' };

const accessors = [...groups.entries()].map(([key, { prop, event, type, tags }]) => {
  const name = accessorNames[key];
  if (!name) throw new Error(`No value accessor name for ${key} (${tags.join(', ')}): add one to accessorNames`);
  const selector = tags.flatMap((t) => [`${t}[ngModel]`, `${t}[formControl]`, `${t}[formControlName]`]).join(',');
  return { name, code: `/** Angular forms support for ${tags.map((t) => `\`<${t}>\``).join(', ')}. */
@Directive({
  selector: '${selector}',
  host: { '(${event})': 'handleChange()', '(focusout)': 'onTouched()' },
  providers: [{ provide: NG_VALUE_ACCESSOR, useExisting: forwardRef(() => ${name}), multi: true }],
})
export class ${name} extends UfValueAccessor<${type}> {
  protected readonly prop = '${prop}';
  protected readonly empty: ${type} = ${emptyValues[type]};
}
` };
});

const accessorsFile = `${header}import { Directive, forwardRef } from '@angular/core';
import { NG_VALUE_ACCESSOR } from '@angular/forms';
import { UfValueAccessor } from '../value-accessor';

${accessors.map((a) => a.code).join('\n')}
export const UF_FORMS = [${accessors.map((a) => a.name).join(', ')}] as const;
`;
await writeFile(new URL('value-accessors.ts', outDir), accessorsFile);

console.log(`angular: generated ${elements.length} component(s), ${accessors.length} value accessor(s)`);
